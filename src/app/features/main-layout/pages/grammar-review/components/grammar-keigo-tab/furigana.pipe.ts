// Cores
import { Pipe, PipeTransform } from '@angular/core';
// Utils
import { createFurigana } from '../../furigana.util';

/**
 * 敬語頁用的假名標註表。`{漢字|よみ}` 標出要加讀音的部分，其餘（送り仮名）照原樣。
 * 只收這一頁出現的日文詞，中文說明裡的漢字不會被標註。
 */
const ENTRIES: readonly string[] = [
  // 特殊動詞與敬語動詞
  'お{越|こ}し', 'お{見|み}えに', '{見|み}えで', '{伺|うかが}', '{申|もう}し{上|あ}げる', '{申|もう}し{訳|わけ}', '{申|もう}し',
  '{申|もう}す', '{申|もう}しました', '{召|め}し{上|あ}がる', '{召|め}し', 'ご{覧|らん}', '{拝見|はいけん}', '{存|ぞん}じ{上|あ}げる',
  '{存|ぞん}じ', '{承|うけたまわ}る', '{目|め}にかかる', '{差|さ}し{上|あ}げる', '{頂戴|ちょうだい}', '{参|まい}',
  '{行|い}', '{来|こ}られる', '{来|く}', '{言|い}う', '{知|し}る', '{聞|き}く', '{見|み}る', '{会|あ}う', '{着|き}る', '{寝|ね}る',
  '{食|た}べる', '{休|やす}み',
  // 人・物・場所
  '{先生|せんせい}', '{資料|しりょう}', 'お{客様|きゃくさま}', '{客様|きゃくさま}', '{山下様|やましたさま}', '{社長|しゃちょう}',
  '{課長|かちょう}', '{部長|ぶちょう}', '{山田|やまだ}', '{田中|たなか}', '{受付|うけつけ}', '{荷物|にもつ}', '{部屋|へや}',
  '{東京|とうきょう}', '{新聞|しんぶん}', '{写真|しゃしん}', '{電話|でんわ}', '{家|いえ}', '{宅|たく}',
  // 動作
  '{送|おく}', '{待|ま}ち', '{出|で}かけ', '{外出|がいしゅつ}', '{外|はず}し', '{確認|かくにん}', '{読|よ}', '{利用|りよう}',
  '{持|も}ち', '{案内|あんない}', '{届|とど}け', '{撮|と}ら', '{使|つか}わ', '{説明|せつめい}', '{教|おし}え', '{了承|りょうしょう}',
  '{礼|れい}', '{話|はな}', '{今|いま}', '{明日|あした}', '{本日|ほんじつ}', '{私|わたし}', '{越|こ}し',
  '{飲|の}む', '{見|み}', '{待|ま}', '{取|と}り',
];

const convert = createFurigana(ENTRIES);

/** 把日文字串中已收錄的詞加上 `<ruby>` 讀音，回傳可給 `[innerHTML]` 的 HTML */
export function addFurigana(text: string): string {
  return convert(text);
}

@Pipe({ name: 'furigana', standalone: true })
export class FuriganaPipe implements PipeTransform {
  transform(value: string | null | undefined): string {
    return value ? addFurigana(value) : '';
  }
}
